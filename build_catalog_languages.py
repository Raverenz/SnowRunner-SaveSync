"""Generate only labels actually used by our offline catalogs, not whole game language files."""
import re,zipfile,sys
from pathlib import Path
from collections import defaultdict
from prices import PRICES
from catalog import LEVELS,UPGRADES
names={entry['name'] for section in PRICES.values() if isinstance(section,dict) for entry in section.values() if isinstance(entry,dict) and 'name' in entry}
names.update(v for entry in LEVELS.values() for v in entry.values())
names.update(entry['name'] for entry in UPGRADES.values())
languages={'en':'english','de':'german','fr':'french','es':'spanish','pt':'brazilian_portuguese','pl':'polish'}
if len(sys.argv)!=2:
    raise SystemExit('Usage: python build_catalog_languages.py <path-to-initial.pak>')
pak=Path(sys.argv[1])
with zipfile.ZipFile(pak) as archive:
 strings={code:dict(re.findall(r'^([^\s]+)\s+"(.*)"\s*$',archive.read('[strings]/strings_'+name+'.str').decode('utf-16'),re.M)) for code,name in languages.items()}
 reverse=defaultdict(list)
 for key,value in strings['pl'].items():reverse[value.replace('\\"','"')].append(key)
 result={}
 for name in sorted(names):
  keys=reverse.get(name,[])
  if not keys:continue
  candidates=[{code:table.get(key,'').replace('\\"','"') for code,table in strings.items() if code!='pl'} for key in keys]
  candidates=[item for item in candidates if all(item.values())]
  if not candidates:continue
  if len(name)>120 or any(len(value)>120 for item in candidates for value in item.values()):continue
  # Only identical translations for an ambiguous Polish label are accepted.
  if any(item!=candidates[0] for item in candidates):continue
  result[name]=candidates[0]
Path('catalog_languages.py').write_text('"""Localized labels for the existing price/upgrade catalog. Generated by build_catalog_languages.py."""\nCATALOG_LABELS = '+repr(result)+'\n',encoding='utf-8')
print('Localized catalog labels:',len(result))
